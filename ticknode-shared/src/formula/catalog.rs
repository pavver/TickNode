/// Returns the catalog of supported formula functions.
pub fn catalog() -> &'static [FunctionDoc] {
    CATALOG
}

/// Normalizes function name (e.g. `math::sqrt` -> `sqrt`) and looks up its definition.
pub fn find_function(name: &str) -> Option<&'static FunctionDoc> {
    let clean = name.strip_prefix("math::").unwrap_or(name);
    CATALOG
        .iter()
        .find(|doc| doc.name == clean || doc.aliases.contains(&clean))
}
